"""
Unbound backend (the DNS resolver of this firewall): no external DNS filter needed.

For every group with a profile a Unbound "view" is generated, selected by the source addresses of the
devices (access-control-view). The view contains the SafeSearch rewrites, blocked categories and own
domains of the profile. The generated file lives in /usr/local/etc/unbound.opnsense.d/ and is validated
with 'configctl unbound check' before Unbound is restarted; if validation fails the previous file is
restored, so a mistake can never break DNS.

Not supported by Unbound itself: an adult content filter (use a blocklist in Unbound) and a query log.
"""
import ipaddress
import os
import re

import pc_catalog
from pc_adguard import PREFIX, clean_domains
from pc_common import BackendError, run
from pc_i18n import _

CONF_DIR = '/usr/local/etc/unbound.opnsense.d'
CONF_NAME = 'parentalcontrol.conf'
HEADER = '# Generated by os-parentalcontrol - do not edit; changes are overwritten.\n'


class UnboundLocal:
    def __init__(self, conf_dir=None, runner=None):
        self.conf_dir = conf_dir or CONF_DIR
        self.path = os.path.join(self.conf_dir, CONF_NAME)
        self.run = runner or run

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False

    def describe(self):
        return _('Unbound (this firewall)')

    def read(self):
        try:
            with open(self.path) as handle:
                return handle.read()
        except OSError:
            return None

    def write(self, text):
        os.makedirs(self.conf_dir, exist_ok=True)
        with open(self.path + '.tmp', 'w') as handle:
            handle.write(text)
        os.replace(self.path + '.tmp', self.path)

    def remove(self):
        try:
            os.remove(self.path)
        except FileNotFoundError:
            pass

    def check(self):
        """Validate the complete Unbound configuration; returns (ok, output)."""
        result = self.run(['/usr/local/sbin/configctl', 'unbound', 'check'])
        output = ((result.stdout or '') + (result.stderr or '')).strip()
        ok = 'no errors' in output.lower() or (result.returncode == 0 and 'error' not in output.lower())
        return ok, output

    def restart(self):
        self.run(['/usr/local/sbin/configctl', 'unbound', 'restart'])

    def test(self):
        os.makedirs(self.conf_dir, exist_ok=True)
        if not os.access(self.conf_dir, os.W_OK):
            raise BackendError(_('cannot write to %s') % self.conf_dir)
        ok, output = self.check()
        if not ok:
            raise BackendError(_('Unbound reports an error in its current configuration: %s') % output[:200])
        return _('Unbound (this firewall): configuration directory is writable and valid')


def slug(name, used):
    base = re.sub(r'[^a-z0-9]+', '_', name[len(PREFIX):].lower() if name.startswith(PREFIX) else name.lower()).strip('_')
    ident, n = 'pc_' + (base or 'group'), 1
    while ident in used:
        n += 1
        ident = 'pc_%s_%d' % (base or 'group', n)
    used.add(ident)
    return ident


def source_address(ip):
    addr = ipaddress.ip_address(ip)
    return '%s/%d' % (addr, 32 if addr.version == 4 else 128)


def view_rules(profile):
    """The local-zone/local-data lines of one profile, plus warnings."""
    warnings = []
    blocked = set(pc_catalog.category_domains(profile['categories'])) | set(clean_domains(profile['blocked_domains']))
    allowed = set(clean_domains(profile['allowed_domains']))
    lines = []
    for domain in sorted(blocked - allowed):
        lines.append('    local-zone: "%s." always_nxdomain' % domain)
    for domain in sorted(allowed):
        lines.append('    local-zone: "%s." transparent' % domain)
    if profile['safesearch']:
        for host, target in sorted(pc_catalog.SAFESEARCH.items()):
            if pc_catalog.covered(host, blocked - allowed):
                continue                                    # blocked anyway: do not undo the block
            lines.append('    local-zone: "%s." transparent' % host)
            lines.append('    local-data: "%s. 300 IN CNAME %s."' % (host, target))
    if profile['parental']:
        warnings.append(_('Unbound has no adult content filter: add a blocklist to Unbound instead'))
    if profile.get('backend_groups'):
        warnings.append(_('Groups in the filter backend are only used by Pi-hole'))
    return lines, warnings


def render(desired):
    """The full configuration text and the warnings for the desired state."""
    if not desired['clients']:
        return '', []
    used, warnings = set(), []
    access, views = [], []
    for name in sorted(desired['clients']):
        want = desired['clients'][name]
        ident = slug(name, used)
        for ip in sorted(want['ids']):
            access.append('    access-control-view: %s %s' % (source_address(ip), ident))
        rules, warn = view_rules(want['profile'])
        warnings += [w for w in warn if w not in warnings]
        views.append('view:\n    name: "%s"\n    view-first: yes\n%s' % (ident, '\n'.join(rules)))
    return HEADER + 'server:\n' + '\n'.join(access) + '\n' + '\n'.join(views) + '\n', warnings


def sync(api, desired):
    report = {'added': 0, 'updated': 0, 'deleted': 0, 'rules': False, 'warnings': []}
    text, report['warnings'] = render(desired)
    keep = desired.get('keep') or set()
    current = api.read()
    if not text and keep and current is not None:
        return report                                      # groups without known addresses: keep what we have
    if text == (current or ''):
        return report
    if not text:
        api.remove()
        api.restart()
        report.update(deleted=1, rules=True)
        return report
    api.write(text)
    ok, output = api.check()
    if not ok:
        if current is None:
            api.remove()
        else:
            api.write(current)
        raise BackendError(_('Unbound rejected the generated configuration: %s') % output[:200])
    api.restart()
    report.update(added=1 if current is None else 0, updated=0 if current is None else 1, rules=True)
    return report
